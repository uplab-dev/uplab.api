<?php

namespace Uplab\Api\Enums;

/**
 * HTTP-статусы, которыми отвечает API модуля.
 *
 * Единственный источник кодов ответа: в коде используется `HttpStatus::CASE`, а не число.
 * Так статус нельзя опечатать, а по использованию кейса видно все места, где он возвращается.
 *
 * Куда попадает значение:
 *
 * - {@see \Uplab\Api\Exception\ApiException} — намеренная клиентская ошибка (`4xx`), ответ
 *   в формате RFC 9457 (`application/problem+json`);
 * - `setErrorResponse()` / `setStatus()` в сервисах — ожидаемые ошибки выборки
 *   (не найдено, нет зависимого модуля, нет прав);
 * - {@see \Uplab\Api\Controller\BaseController} — статус ответа целиком.
 *
 * Enum типизирован `int`, поэтому там, где ядро Битрикс ждёт число, передаётся `->value`.
 * Список намеренно ограничен статусами, которые модуль действительно возвращает: добавляйте
 * кейс вместе с кодом, который его использует, а не «на будущее».
 */
enum HttpStatus: int
{
    /** Успешный запрос: сервисные endpoint-ы отдают данные, административные — конверт `{status, data, errors}`. */
    case OK = 200;

    /** Ресурс создан. */
    case CREATED = 201;

    /** Успешно, тела ответа нет. */
    case NO_CONTENT = 204;

    /**
     * Ошибка в параметрах запроса: нарушены лимиты
     * ({@see \Uplab\Api\Utils\Config\BaseConfig}), некорректный JSON или значение параметра.
     */
    case BAD_REQUEST = 400;

    /** Требуется авторизация Битрикс (административные endpoint-ы контента). */
    case UNAUTHORIZED = 401;

    /**
     * Доступ запрещён: не пройден фильтр Origin/IP
     * ({@see \Uplab\Api\ActionFilter\ApiAccessFilter}), нет права чтения HL-блока,
     * не пройдена проверка CSRF-токена.
     */
    case FORBIDDEN = 403;

    /** Запрошенная сущность не найдена: инфоблок, HL-блок, элемент, раздел, форма, страница. */
    case NOT_FOUND = 404;

    /** Метод запроса не поддерживается маршрутом. */
    case METHOD_NOT_ALLOWED = 405;

    /** Тело запроса больше допустимого (лимит `BaseController::MAX_JSON_BODY_BYTES`). */
    case PAYLOAD_TOO_LARGE = 413;

    /** Данные синтаксически верны, но не проходят предметную проверку. */
    case UNPROCESSABLE_ENTITY = 422;

    /**
     * Не установлен модуль Битрикс, от которого зависит endpoint
     * (`iblock`, `highloadblock`, `form`, `search`).
     */
    case FAILED_DEPENDENCY = 424;

    /** Превышено ограничение частоты запросов. */
    case TOO_MANY_REQUESTS = 429;

    /**
     * Необработанное исключение или ошибка: тело RFC 9457 без раскрытия внутренностей,
     * детали — в Журнал событий (тип `UPLAB_API_INTERNAL_ERROR`).
     */
    case INTERNAL_SERVER_ERROR = 500;

    /** Сервис временно недоступен. */
    case SERVICE_UNAVAILABLE = 503;
}
